const DICTS: Record<Lang, Record<Key, string>> = { en, fr, ar };

export function deviceLang(): Lang {
  try {
    const loc = Intl.DateTimeFormat().resolvedOptions().locale.toLowerCase();
    if (loc.startsWith('ar')) return 'ar';
    if (loc.startsWith('fr')) return 'fr';
  } catch {
    // no Intl: English
  }
  return 'en';
}

let current: Lang = deviceLang();
export const setLang = (l: Lang | 'auto') => (current = l === 'auto' ? deviceLang() : l);
export const lang = () => current;

export function t(key: Key, params?: Record<string, string | number>) {
  let s = DICTS[current][key] ?? en[key];
  if (params) for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, typeof v === 'number' ? fmt(v) : v);
  return s;
}

// Numbers with the language's grouping (1,234 / 1 234), always in Western digits like Moroccan signs.
export const fmt = (n: number) => n.toLocaleString(current === 'fr' ? 'fr-FR' : 'en-US');

