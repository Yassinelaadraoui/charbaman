"""Turn the high-poly taxi glTF into a light, flat-shaded mesh module for the game.

Usage: python3 scripts/convert-taxi.py path/to/scene.gltf src/game/three/taxiMesh.ts
Needs: pip install trimesh pyfqmr numpy

The source model has ~590k triangles; a phone runner needs a few thousand.
Parts are merged by material into colour groups, the cabin interior is dropped,
and each group is decimated. "body" is recoloured per city at runtime.
"""
import json
import sys
from collections import defaultdict

import numpy as np
import pyfqmr
import trimesh

src, dst = sys.argv[1], sys.argv[2]

GROUPS = {
    'body': ['redgloss', 'whitegloss', 'TAXI2.001', 'TAXI3', 'TAXI4'],
    'dark': ['matte_colors.001', 'matte_colors.002', 'black_rubber.001', 'weatherstrip', 'ae_bottom', 'Material_2061'],
    'tyre': ['TireMaterial', 'tire2'],
    'glass': ['glass', 'glass.tinted', 'glass.001'],
    'chrome': ['grills', 'crome', 'chrome.001', 'chrome.002', 'mirror', 'metal'],
    'rim': ['supra_drift_rims', 'supra_disc.002', 'caliper.002'],
    'headlight': ['glass.002'],
    'taillight': ['redlights'],
    'sign': ['TAXI1', 'Material.001'],
}
TARGET = {'body': 2200, 'dark': 700, 'tyre': 480, 'glass': 260, 'chrome': 420, 'rim': 360, 'headlight': 60, 'taillight': 60, 'sign': 48}
LENGTH = 3.8  # metres, a Moroccan petit taxi is a small hatchback

lookup = {m: g for g, ms in GROUPS.items() for m in ms}
scene = trimesh.load(src, force='scene')
parts = defaultdict(list)
for mesh in scene.dump(concatenate=False):
    group = lookup.get(getattr(mesh.visual.material, 'name', None))
    if group:  # anything unlisted is cabin interior, invisible behind the glass
        parts[group].append(trimesh.Trimesh(mesh.vertices, mesh.faces, process=False))

merged = {}
for g, ms in parts.items():
    m = trimesh.util.concatenate(ms)
    # Weld duplicated vertices (glTF splits them per normal/UV) or the decimator eats the shell.
    m = trimesh.Trimesh(np.round(m.vertices, 4), m.faces, process=True)
    m.merge_vertices(digits_vertex=3)
    merged[g] = m
allv = np.vstack([m.vertices for m in merged.values()])
lo, hi = allv.min(axis=0), allv.max(axis=0)
scale = LENGTH / (hi[2] - lo[2])
centre = np.array([(lo[0] + hi[0]) / 2, lo[1], (lo[2] + hi[2]) / 2])

CELL = 0.065  # metres in the final model: vertex-clustering grid, gives a clean low-poly look


def cluster(v, f, cell):
    """Snap vertices to a grid and merge each cell into one vertex. Robust on messy,
    non-manifold source meshes where edge-collapse decimators stall."""
    keys = np.floor(v / cell).astype(np.int64)
    uniq, inverse = np.unique(keys, axis=0, return_inverse=True)
    inverse = inverse.reshape(-1)
    sums = np.zeros((len(uniq), 3))
    np.add.at(sums, inverse, v)
    counts = np.bincount(inverse, minlength=len(uniq))[:, None]
    nv = sums / counts
    nf = inverse[f]
    keep = (nf[:, 0] != nf[:, 1]) & (nf[:, 1] != nf[:, 2]) & (nf[:, 0] != nf[:, 2])
    nf = np.unique(np.sort(nf[keep], axis=1), axis=0, return_index=True)[1]
    return nv, inverse[f][keep][np.sort(nf)]


out = {}
for g, m in merged.items():
    v = (m.vertices - centre) * scale
    v, f = cluster(v, m.faces, CELL * (0.7 if g in ('rim', 'headlight', 'taillight', 'sign') else 1))
    if len(f) > TARGET[g]:
        s = pyfqmr.Simplify()
        s.setMesh(v, f)
        s.simplify_mesh(target_count=TARGET[g], aggressiveness=5, preserve_border=True, verbose=False)
        v, f, _ = s.getMesh()
    out[g] = {'p': [round(float(x), 3) for x in v.reshape(-1)], 'i': [int(x) for x in f.reshape(-1)]}
    print(g, len(m.faces), '->', len(f))

with open(dst, 'w') as fh:
    fh.write('// Generated by scripts/convert-taxi.py. Do not edit by hand.\n')
    fh.write('// "Hong Kong Taxi" by Goedude (sketchfab.com/Goedude), CC-BY-4.0, decimated and recoloured.\n')
    fh.write('// Metres, wheels on y=0, front toward +z. p = positions, i = triangle indices.\n')
    fh.write('export const TAXI_PARTS: Record<string, { p: number[]; i: number[] }> = ')
    fh.write(json.dumps(out, separators=(',', ':')))
    fh.write(';\n')
