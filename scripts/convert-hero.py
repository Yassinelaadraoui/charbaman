"""Convert the segmented hero OBJ (one object per body part) into a TS module.

Usage: python3 scripts/convert-hero.py assets/models/hero.obj src/game/three/heroMesh.ts

Each part becomes a flat triangle list in metres, feet on y=0, facing +z.
Part names are assigned from where each piece sits on the body, so any model
split the same way (16 parts, T-pose) can be dropped in.
"""
import json
import sys

src, dst = sys.argv[1], sys.argv[2]
verts = []
parts = {}
cur = None
for line in open(src):
    t = line.split()
    if not t:
        continue
    if t[0] == 'o':
        cur = t[1]
        parts[cur] = []
    elif t[0] == 'v':
        verts.append(tuple(map(float, t[1:4])))
    elif t[0] == 'f':
        idx = [int(p.split('/')[0]) - 1 for p in t[1:]]
        for i in range(1, len(idx) - 1):  # fan-triangulate
            parts[cur].extend([idx[0], idx[i], idx[i + 1]])

ys = [v[1] for v in verts]
height = max(ys) - min(ys)
scale = 1.8 / height
floor = min(ys)


def bbox(ids):
    pts = [verts[i] for i in ids]
    return [min(p[k] for p in pts) for k in range(3)], [max(p[k] for p in pts) for k in range(3)]


def classify(ids):
    lo, hi = bbox(ids)
    cx = (lo[0] + hi[0]) / 2
    cy = (lo[1] + hi[1]) / 2
    side = 'L' if cx < 0 else 'R'
    h = (cy - floor) / height  # 0 feet .. 1 head
    if abs(cx) > 0.1 * height and h > 0.6:
        reach = abs(cx) / (height * 0.55)
        if reach > 0.85:
            return 'hand' + side
        if reach > 0.55:
            return 'forearm' + side
        return 'upperArm' + side
    if h > 0.9:
        return 'head'
    if h > 0.82 and hi[0] - lo[0] < 0.1 * height:
        return 'neck'
    if h > 0.6:
        return 'torso'
    if h > 0.5 and hi[0] - lo[0] > 0.15 * height:
        return 'pelvis'
    if h > 0.4:
        return 'thigh' + side
    if h > 0.1:
        return 'shin' + side
    return 'foot' + side


out = {}
for name, ids in parts.items():
    label = classify(ids)
    assert label not in out, f'duplicate part {label}'
    flat = []
    for i in ids:
        x, y, z = verts[i]
        flat += [round(x * scale, 4), round((y - floor) * scale, 4), round(z * scale, 4)]
    out[label] = flat

print(sorted(out))
with open(dst, 'w') as f:
    f.write('// Generated by scripts/convert-hero.py from assets/models/hero.obj. Do not edit by hand.\n')
    f.write('// Triangle lists in metres: feet on y=0, facing +z, T-pose.\n')
    f.write('export const HERO_PARTS: Record<string, number[]> = ')
    f.write(json.dumps(out, separators=(',', ':')))
    f.write(';\n')
